"""Compute every answer the one-button calculator can make from 2 within a few presses.

A press combines two numbers already in the notebook (the same number may fill both
boxes). Notebooks are explored exhaustively up to MAX_PRESSES presses with 40-digit
arithmetic. Presses whose exponential argument exceeds 700 (answers beyond about
10^304, past ordinary computer numbers) are left out, so the true picture is fuller.

Writes the reachable-values strips into the essay (between the REACHABLE markers),
a copy of that snippet, and a JSON summary.
This is a numerical illustration of the density theorem, not a proof of it.
"""
from pathlib import Path
import json
import sys
import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'proofs/positive-seeds/reachable-from-2.json'
SNIPPET = ROOT / 'assets/essays/calculator/reachable-strips.html'
ESSAY = ROOT / 'essays/what-one-operation-can-build.html'
MARKERS = ('<!-- REACHABLE_START -->', '<!-- REACHABLE_END -->')
mp.mp.dps = 40
MAX_PRESSES = int(sys.argv[1]) if len(sys.argv) > 1 else 8
EXP_LIMIT = 700
WINDOW = (-4, 8)          # main strip
ZOOM = (0.9, 1.1)         # inset around 1
COLUMNS = 600             # one mark per occupied slice


def key(v):
    return mp.nstr(v, 25)


def press(a, b):
    if b <= 0 or a > EXP_LIMIT:
        return None
    return mp.exp(a) - mp.log(b)


values = {key(mp.mpf(2)): mp.mpf(2)}
first_seen = {key(mp.mpf(2)): 0}
frontier = {(key(mp.mpf(2)),)}
per_depth = []
for depth in range(1, MAX_PRESSES + 1):
    nxt = set()
    for book in frontier:
        nums = [values[k] for k in book]
        for a in nums:
            for b in nums:
                v = press(a, b)
                if v is None:
                    continue
                k = key(v)
                if k in book:
                    continue
                if k not in values:
                    values[k] = v
                    first_seen[k] = depth
                nxt.add(tuple(sorted(book + (k,))))
    frontier = nxt
    per_depth.append(len(frontier))
    print(f'presses <= {depth}: {len(frontier):,} notebooks, {len(values):,} distinct answers', flush=True)


def column_marks(lo, hi, depth):
    cols = set()
    width = (hi - lo) / COLUMNS
    count = 0
    for k, v in values.items():
        if first_seen[k] <= depth and lo <= v <= hi:
            count += 1
            cols.add(min(COLUMNS - 1, int((v - lo) / width)))
    return count, sorted(cols)


def path_for(cols):
    return ''.join(f'M{c + .5:g} 0V10' for c in cols)


rows, summary = [], []
for depth in range(1, MAX_PRESSES + 1):
    count, cols = column_marks(*WINDOW, depth)
    rows.append((depth, count, cols))
    summary.append({'presses_at_most': depth, 'numbers_in_window': count, 'occupied_slices': len(cols)})
zcount, zcols = column_marks(*ZOOM, MAX_PRESSES)
closest = min(values.values(), key=lambda v: abs(v - 1))

parts = ['<!-- Generated by tools/build_reachable_figure.py; do not edit by hand. -->',
         '<div class="reach-strips" role="img" aria-labelledby="reach-title reach-desc">']
for depth, count, cols in rows:
    label = 'press' if depth == 1 else 'presses'
    parts.append(f'<div class="reach-row"><p class="reach-label"><span>Up to {depth} {label}</span>'
                 f'<span>{count:,} {"number" if count == 1 else "numbers"} in view</span></p>'
                 f'<svg viewBox="0 0 {COLUMNS} 10" preserveAspectRatio="none" aria-hidden="true">'
                 f'<path d="{path_for(cols)}"/></svg></div>')
ticks = ''.join(f'<span style="left:{(t - WINDOW[0]) / (WINDOW[1] - WINDOW[0]) * 100:g}%">{t}</span>'
                for t in range(WINDOW[0], WINDOW[1] + 1, 2))
parts.append(f'<div class="reach-axis" aria-hidden="true">{ticks}</div>')
parts.append('</div>')
parts.append(f'<div class="reach-zoom"><p class="reach-label"><span>Zoom in 60× around 1 · up to {MAX_PRESSES} presses</span>'
             f'<span>{zcount:,} numbers in view</span></p>'
             f'<svg viewBox="0 0 {COLUMNS} 10" preserveAspectRatio="none" aria-hidden="true"><path d="{path_for(zcols)}"/></svg>'
             f'<div class="reach-axis" aria-hidden="true"><span style="left:0%">0.9</span><span style="left:50%">1</span>'
             f'<span style="left:100%">1.1</span></div></div>')
snippet = '\n'.join(parts) + '\n'
SNIPPET.write_text(snippet)
essay = ESSAY.read_text()
before, rest = essay.split(MARKERS[0], 1)
_, after = rest.split(MARKERS[1], 1)
ESSAY.write_text(before + MARKERS[0] + '\n' + snippet + MARKERS[1] + after)

DATA.write_text(json.dumps({
    'seed': '2', 'precision_decimal_digits': 40, 'max_presses': MAX_PRESSES,
    'rule': 'A press applies F(a,b)=exp(a)-ln(b) to two notebook entries; b must be positive.',
    'omitted': f'Presses with exponential argument above {EXP_LIMIT} (answers beyond about 1e304).',
    'scope': 'Exhaustive over notebooks within the stated limits. Numerical illustration of density; not a proof.',
    'window': list(WINDOW), 'zoom_window': list(ZOOM), 'slices': COLUMNS,
    'notebooks_per_depth': per_depth, 'rows': summary,
    'zoom_numbers': zcount, 'closest_to_one': mp.nstr(closest, 20),
    'distinct_numbers_total': len(values)}, indent=2) + '\n')
print('closest to 1:', mp.nstr(closest, 15))
print('rows:', [(r['presses_at_most'], r['numbers_in_window'], r['occupied_slices']) for r in summary], 'zoom', zcount)
